/**
 * The in-rpx gateway entry must merge `sites.d/*.json` fragments exactly the
 * way ts-cloud's generated assembler did on the box, so a box switching from
 * the compiled launcher to the prebuilt `rpx gateway` binary sees the same
 * routes, cert set, ACME allowlist and origin guard.
 *
 * Parity is checked against the assembler itself: `assemblerSource` below is
 * the output of ts-cloud's `renderRpxAssembler(sitesDir, certsDir)`
 * (packages/ts-cloud/src/drivers/shared/rpx-gateway.ts at ts-cloud a817a794)
 * with two edits that cannot change the merged config: the `startProxies`
 * import and call are swapped for a default export of the config it would
 * have started, and dash punctuation in its comments and log strings is
 * normalized to hyphens. Fixtures are shaped like `buildRpxConfig`
 * output (static routes with the object form, a server-app route, an auto-www
 * redirect, productionCerts, onDemandTls, acmeChallengeWebroot, originGuard).
 */
